def resolve_retry_config(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts):
    presets = {
        "sdk_default": {"initial_interval": 1.0, "backoff_coefficient": 2.0, "maximum_interval": 100.0, "maximum_attempts": 0},
        "fast_idempotent": {"initial_interval": 0.1, "backoff_coefficient": 2.0, "maximum_interval": 5.0, "maximum_attempts": 10},
        "slow_external": {"initial_interval": 5.0, "backoff_coefficient": 2.0, "maximum_interval": 300.0, "maximum_attempts": 8},
        "linear": {"initial_interval": 10.0, "backoff_coefficient": 1.0, "maximum_interval": 100.0, "maximum_attempts": 5},
    }
    if preset in presets:
        p = presets[preset]
        return {
            "initial_interval": p["initial_interval"],
            "backoff_coefficient": p["backoff_coefficient"],
            "maximum_interval": p["maximum_interval"],
            "maximum_attempts": p["maximum_attempts"],
        }
    return {
        "initial_interval": initial_interval,
        "backoff_coefficient": backoff_coefficient,
        "maximum_interval": maximum_interval,
        "maximum_attempts": maximum_attempts,
    }


def retry_schedule(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts, attempt_duration):
    cfg = resolve_retry_config(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts)
    ii = cfg["initial_interval"]
    bc = cfg["backoff_coefficient"]
    mi = cfg["maximum_interval"]
    ma = cfg["maximum_attempts"]
    n_attempts = ma if ma and ma > 0 else 20
    n_attempts = int(min(n_attempts, 20))
    if n_attempts < 1:
        n_attempts = 1
    attempt_numbers = []
    starts = []
    intervals = []
    cumulative = []
    capped_at = None
    start = 0.0
    for n in range(1, n_attempts + 1):
        if n == 1:
            interval = 0.0
        else:
            raw = ii * (bc ** (n - 2))
            interval = raw if raw < mi else mi
            if capped_at is None and raw >= mi:
                capped_at = n
            start = start + attempt_duration + interval
        attempt_numbers.append(n)
        starts.append(round(start, 3))
        intervals.append(round(interval, 3))
        cumulative.append(round(start + attempt_duration, 3))
    total_elapsed = starts[-1] if starts else 0.0
    return {
        "attempt_numbers": attempt_numbers,
        "starts": starts,
        "intervals": intervals,
        "cumulative": cumulative,
        "total_elapsed": round(total_elapsed, 3),
        "n_attempts": n_attempts,
        "capped_at": capped_at if capped_at is not None else n_attempts,
    }


def retry_table_view(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts, attempt_duration):
    sched = retry_schedule(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts, attempt_duration)
    row_labels = [str(n) for n in sched["attempt_numbers"]]
    col_labels = ["Start (s)", "Interval before (s)", "Elapsed after (s)"]
    cells = []
    for i in range(len(row_labels)):
        cells.append([sched["starts"][i], sched["intervals"][i], sched["cumulative"][i]])
    caption = (
        "Each row is one attempt. Start is the wall-clock time the attempt begins; interval before is the "
        "backoff wait after the previous attempt failed, not before it starts. Attempt " + str(sched["n_attempts"]) +
        " begins at " + str(sched["total_elapsed"]) + "s, which is attempt duration plus every prior interval, "
        "not just the sum of intervals."
    )
    return {
        "kind": "grid",
        "row_labels": row_labels,
        "col_labels": col_labels,
        "cells": cells,
        "caption": caption,
    }


def retry_bars_view(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts, attempt_duration):
    sched = retry_schedule(preset, initial_interval, backoff_coefficient, maximum_interval, maximum_attempts, attempt_duration)
