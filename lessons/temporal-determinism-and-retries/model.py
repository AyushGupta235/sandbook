def audit_command_log(commands):
    """Inspect a captured list of workflow commands for replay-safety signals.

    `commands` is a list of dicts, each shaped like one of:
      {"op": "uuid4", "value": ...}
      {"op": "now", "value": ...}
      {"op": "sleep", "seconds": ...}
      {"op": "execute_activity", "activity": ..., "arg": {...},
       "start_to_close": number or None, "maximum_attempts": int or None}

    Returns a plain dict summarizing the sequence so a caller can assert on
    it without re-walking the raw log.
    """
    op_sequence = []
    has_activity = False
    start_to_close = None
    maximum_attempts = None
    idem_key = None

    for entry in commands:
        if not isinstance(entry, dict):
            continue
        op = entry.get("op")
        op_sequence.append(op)
        if op == "execute_activity":
            has_activity = True
            start_to_close = entry.get("start_to_close")
            maximum_attempts = entry.get("maximum_attempts")
            arg = entry.get("arg")
            if isinstance(arg, dict):
                idem_key = arg.get("idem_key")

    has_bounded_retries = isinstance(maximum_attempts, int) and maximum_attempts > 0

    return {
        "op_sequence": op_sequence,
        "has_activity": has_activity,
        "start_to_close": start_to_close,
        "maximum_attempts": maximum_attempts,
        "idem_key": idem_key,
        "has_timeout": start_to_close is not None,
        "has_bounded_retries": has_bounded_retries,
    }
