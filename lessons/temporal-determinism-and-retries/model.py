def replay_sim_init():
    return {
        "step": 0,
        "history": ["WorkflowExecutionStarted"],
        "line": "(workflow function entered)",
        "commands_emitted": [],
        "is_replaying": False,
        "worker": "W1",
        "note": "Task 1 begins. History holds one event so far, WorkflowExecutionStarted. The worker is about to run the workflow code live for the first time ever.",
        "done": False,
    }


def replay_sim_step(state):
    script = replay_script_data()
    idx = state.get("step", 0)
    if idx >= len(script):
        new_state = dict(state)
        new_state["done"] = True
        return new_state
    entry = script[idx]
    new_step = idx + 1
    new_state = dict(entry)
    new_state["step"] = new_step
    new_state["done"] = new_step >= len(script)
    return new_state


