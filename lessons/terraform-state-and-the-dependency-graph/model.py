def bwd_graph_edges():
    return [
        ["vpc", "subnet"],
        ["vpc", "security_group"],
        ["vpc", "route_table"],
        ["subnet", "instance_1"],
        ["security_group", "instance_1"],
        ["subnet", "instance_2"],
        ["security_group", "instance_2"],
        ["subnet", "instance_3"],
        ["security_group", "instance_3"],
        ["instance_1", "eip"],
        ["subnet", "load_balancer"],
        ["instance_1", "load_balancer"],
        ["instance_2", "load_balancer"],
        ["instance_3", "load_balancer"],
    ]


def bwd_topo_create_order():
    nodes = bwd_graph_nodes()
    edges = bwd_graph_edges()
    indeg = {n: 0 for n in nodes}
    adj = {n: [] for n in nodes}
    for a, b in edges:
        adj[a].append(b)
        indeg[b] = indeg.get(b, 0) + 1
    ready = sorted([n for n in nodes if indeg[n] == 0])
    order = []
    while ready:
        ready.sort()
        n = ready.pop(0)
        order.append(n)
        for m in adj[n]:
            indeg[m] -= 1
            if indeg[m] == 0:
                ready.append(m)
    return order


def bwd_downstream(node):
    edges = bwd_graph_edges()
    adj = {}
    for a, b in edges:
        adj.setdefault(a, []).append(b)
    seen = set()
    result = []
    stack = [node]
    while stack:
        cur = stack.pop()
        for nxt in sorted(adj.get(cur, [])):
            if nxt not in seen:
                seen.add(nxt)
                result.append(nxt)
                stack.append(nxt)
    return result


def bwd_mode_queue(mode):
    create_order = bwd_topo_create_order()
    destroy_order = list(reversed(create_order))
    if mode == "full_destroy":
        return destroy_order
    if mode == "replace_instance3":
        target = "instance_3"
    else:
        target = "vpc"
    downstream = set(bwd_downstream(target))
    queue = [n for n in destroy_order if n in downstream]
    queue.append(target)
    return queue


def backwards_destroy_init(mode):
    queue = bwd_mode_queue(mode)
    return {
        "mode": mode,
        "queue": queue,
        "total": len(queue),
        "step_num": 0,
        "affected": [],
        "done": len(queue) == 0,
    }


def backwards_destroy_step(state):
    if state.get("done"):
        return dict(state)
    queue = state["queue"]
    idx = state["step_num"]
    node = queue[idx]
    new_affected = state["affected"] + [node]
    new_step = idx + 1
    new_done = new_step >= len(queue)
    return {
        "mode": state["mode"],
        "queue": queue,
        "total": state["total"],
        "step_num": new_step,
        "affected": new_affected,
        "done": new_done,
    }


def backwards_destroy_view(state):
    destroy_order = list(reversed(bwd_topo_create_order()))
    affected = state.get("affected", [])
    mode = state.get("mode", "replace_vpc")
    total = state.get("total", len(destroy_order))
    labels = destroy_order
    values = [1 if n in affected else 0 for n in destroy_order]
    if mode == "full_destroy":
        caption = (
            "Full destroy walks the nine-node graph in reverse. Leaves like load_balancer go "
            "first, the three instances and eip clear before subnet and security_group, and vpc, "
            "the node everything else traces back to, goes last. "
            + str(len(affected)) + " of 9 resources destroyed so far."
        )
    elif mode == "replace_instance3":
        caption = (
            "instance_3 is marked force-new. Its downstream reachable set is one resource, "
            "load_balancer, so only two resources move in total. "
            + str(len(affected)) + " of " + str(total) + " affected resources handled so far."
        )
    else:
        caption = (
            "vpc is marked force-new. Nothing downstream can keep existing once vpc is gone, so "
            "all eight resources that trace back to vpc are destroyed first, in the same order a "
            "full destroy would use, and then vpc itself goes before everything rebuilds. "
            + str(len(affected)) + " of " + str(total) + " affected resources handled so far."
        )
    return {
        "kind": "stack",
        "panels": [
            {
                "kind": "bars",
                "labels": labels,
                "values": values,
                "x_label": "resource, in destroy order",
                "y_label": "handled",
                "y_min": 0,
                "y_max": 1,
                "value_format": "d",
                "caption": caption,
            },
            {
                "kind": "scalars",
                "items": [
                    {"label": "step", "value": state.get("step_num", 0)},
                    {"label": "affected so far", "value": len(affected)},
                    {"label": "total to handle", "value": total},
                ],
            },
        ],
    }
