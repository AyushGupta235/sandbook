def grade_edges(submission):
    import re

    text = submission if isinstance(submission, str) else str(submission)

    def parse(cfg_text):
        pattern = re.compile(r'resource\s+"([\w]+)"\s+"([\w]+)"\s*\{(.*?)\n\}', re.DOTALL)
        out = []
        for m in pattern.finditer(cfg_text):
            out.append({"type": m.group(1), "name": m.group(2), "body": m.group(3)})
        return out

    def addr_of(r):
        return f"{r['type']}.{r['name']}"

    try:
        resources = parse(text)
    except Exception:
        return {
            "passed": False,
            "message": "Could not parse the config.",
            "details": [{"label": "parse", "ok": False,
                          "note": "The config text could not be parsed into resource blocks. Check that every block is closed with a line containing only '}'."}],
            "view": None,
        }

    if not resources:
        return {
            "passed": False,
            "message": "No resource blocks were found.",
            "details": [{"label": "parse", "ok": False,
                          "note": "No 'resource \"type\" \"name\" { ... }' blocks were found. Each block's closing brace must sit on its own line."}],
            "view": None,
        }

    addrs = {addr_of(r) for r in resources}
    edges = []
    ref_pairs = set()
    redundant = []

    for r in resources:
        addr = addr_of(r)
        seen = set()
        for rt, rn, ra in re.findall(r'\$\{([\w]+)\.([\w]+)\.([\w]+)\}', r["body"]):
            target = f"{rt}.{rn}"
            if target == addr or target in seen:
                continue
            seen.add(target)
            edges.append((addr, target, "reference"))
            ref_pairs.add((addr, target))

        dep_match = re.search(r'depends_on\s*=\s*\[(.*?)\]', r["body"], re.DOTALL)
        if dep_match:
            for item in re.findall(r'"([\w\.]+)"', dep_match.group(1)):
                if item == addr:
                    continue
                if (addr, item) in ref_pairs:
                    redundant.append((addr, item))
                else:
                    edges.append((addr, item, "depends_on"))

    if redundant:
        frm, to = redundant[0]
        return {
            "passed": False,
            "message": f"{frm} has depends_on = [\"{to}\"] but an expression already reads {to}'s attributes, so that edge exists already.",
            "details": [{
                "label": "redundant depends_on",
                "ok": False,
                "note": f"{frm} already depends on {to} because of an ${{...}} reference in its body. The extra depends_on is inert; remove it.",
            }],
            "view": None,
        }

    graph = {}
    for frm, to, _ in edges:
        graph.setdefault(frm, set()).add(to)
    for a in addrs:
        graph.setdefault(a, set())

    def find_cycle():
        visited = set()
        onstack = []
        onstack_set = set()

        def dfs(node):
            visited.add(node)
            onstack.append(node)
            onstack_set.add(node)
            for nxt in sorted(graph.get(node, [])):
                if nxt in onstack_set:
                    i = onstack.index(nxt)
                    return onstack[i:] + [nxt]
                if nxt not in visited:
                    found = dfs(nxt)
                    if found:
                        return found
            onstack.pop()
            onstack_set.discard(node)
            return None

        for a in sorted(graph.keys()):
            if a not in visited:
                found = dfs(a)
                if found:
                    return found
        return None

    cycle = find_cycle()
    if cycle:
        return {
            "passed": False,
            "message": "The dependency graph has a cycle: " + " -> ".join(cycle),
            "details": [{
                "label": "acyclic",
                "ok": False,
                "note": "A resource graph must be a DAG. Remove one of the references in this cycle: " + " -> ".join(cycle),
            }],
            "view": None,
        }

    pairs = {(f, t) for f, t, _ in edges}
    expected = {
        ("aws_subnet.main", "aws_vpc.main"),
        ("aws_security_group.sg", "aws_vpc.main"),
        ("aws_instance.app", "aws_subnet.main"),
        ("aws_instance.app", "aws_iam_role_policy.policy"),
    }

    vpc_ok = ("aws_subnet.main", "aws_vpc.main") in pairs and ("aws_security_group.sg", "aws_vpc.main") in pairs
    instance_ref_ok = ("aws_instance.app", "aws_subnet.main", "reference") in edges
    policy_dep_ok = ("aws_instance.app", "aws_iam_role_policy.policy", "depends_on") in edges
    exact_ok = pairs == expected

    details = [
        {"label": "subnet and security group reference the vpc", "ok": vpc_ok,
         "note": "aws_subnet.main and aws_security_group.sg must both read ${aws_vpc.main.id} somewhere in their body."},
        {"label": "instance depends on subnet via a reference, not a literal", "ok": instance_ref_ok,
         "note": "aws_instance.app still hardcodes subnet_id as a literal string. Replace it with ${aws_subnet.main.id} so the edge comes from an expression."},
        {"label": "instance depends on the IAM role policy via depends_on", "ok": policy_dep_ok,
         "note": "Add an aws_iam_role_policy resource and put depends_on = [\"aws_iam_role_policy.policy\"] on aws_instance.app. No expression reads the policy's attributes, so only depends_on can create this edge."},
        {"label": "edge set matches exactly, nothing extra or missing", "ok": exact_ok,
         "note": f"Found edges {sorted(pairs)}, expected {sorted(expected)}."},
    ]

    passed = all(d["ok"] for d in details)
    message = "All four edges are present and nothing extra was added." if passed else "The edge set does not match yet."

    view = {
        "kind": "text",
        "text": "Adjacency list:\n" + "\n".join(
            f"{a} -> {', '.join(sorted(graph[a])) if graph[a] else '(no dependencies)'}"
            for a in sorted(graph.keys())
        ),
        "caption": "Each line reads 'this resource depends on these'. Every edge came from a ${...} reference or a depends_on list, never from the order the blocks appear in the file.",
    }

    return {"passed": passed, "message": message, "details": details, "view": view}


