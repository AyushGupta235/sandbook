def dag_schedule(concurrency, duration_profile):
    nodes = ["vpc", "s3_bucket", "subnet_a", "subnet_b", "security_group",
             "instance_1", "instance_2", "instance_3"]
    deps = {
        "vpc": [],
        "s3_bucket": [],
        "subnet_a": ["vpc"],
        "subnet_b": ["vpc"],
        "security_group": ["vpc"],
        "instance_1": ["subnet_a", "security_group"],
        "instance_2": ["subnet_a"],
        "instance_3": ["subnet_b", "security_group"],
    }
    if duration_profile == "vpc_slow":
        durations = {"vpc": 20, "s3_bucket": 3, "subnet_a": 3, "subnet_b": 3,
                     "security_group": 3, "instance_1": 3, "instance_2": 3, "instance_3": 3}
    elif duration_profile == "instances_slow":
        durations = {"vpc": 3, "s3_bucket": 3, "subnet_a": 3, "subnet_b": 3,
                     "security_group": 3, "instance_1": 15, "instance_2": 15, "instance_3": 15}
    else:
        durations = {n: 3 for n in nodes}

    concurrency = max(1, int(concurrency))

    remaining = set(nodes)
    finish_times = {}
    start_times = {}
    running = {}
    time = 0.0
    guard = 0

    while (remaining or running) and guard < 1000:
        guard += 1
        ready = [n for n in nodes if n in remaining and all(d in finish_times for d in deps[n])]
        while ready and len(running) < concurrency:
            n = ready.pop(0)
            start_times[n] = time
            running[n] = time + durations[n]
            remaining.discard(n)
        if not running:
            break
        next_time = min(running.values())
        time = next_time
        done_now = [n for n, t in running.items() if t <= time]
        for n in done_now:
            finish_times[n] = running[n]
            del running[n]

    total_time = max(finish_times.values()) if finish_times else 0.0

    schedule = []
    for n in nodes:
        schedule.append({
            "node": n,
            "start": start_times.get(n, 0.0),
            "end": finish_times.get(n, start_times.get(n, 0.0)),
        })

    return {
        "nodes": nodes,
        "schedule": schedule,
        "total_time": total_time,
        "concurrency": concurrency,
        "duration_profile": duration_profile,
    }


def total_apply_time(concurrency, duration_profile):
    result = dag_schedule(concurrency, duration_profile)
    return float(result["total_time"])


