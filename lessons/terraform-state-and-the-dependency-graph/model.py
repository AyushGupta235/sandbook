def apply_timeline_view(concurrency, duration_profile, shuffle_seed):
    result = dag_schedule(concurrency, duration_profile)
    schedule = result["schedule"]
    total_time = result["total_time"]
    nodes = result["nodes"]
    conc = result["concurrency"]

    bucket_size = 1
    if total_time > 30:
        bucket_size = int(total_time // 30) + 1
    bucket_count = max(1, int(total_time // bucket_size) + 1)
    column_labels = [str(i * bucket_size) for i in range(bucket_count)]

    cells = []
    for row in schedule:
        start = row["start"]
        end = row["end"]
        node_row = []
        for i in range(bucket_count):
            bucket_start = i * bucket_size
            bucket_end = bucket_start + bucket_size
            running = 1 if (start < bucket_end and end > bucket_start) else 0
            node_row.append(running)
        cells.append(node_row)

    grid_panel = {
        "kind": "grid",
        "row_labels": nodes,
        "column_labels": column_labels,
        "cells": cells,
        "x_label": "seconds since apply started",
        "y_label": "resource",
        "caption": "Each row is a resource; a filled cell means it is applying during that second. Rows fill in whatever order the graph allows, never in the order the file lists them.",
    }

    shuffle_orders = {
        0: ["vpc", "subnet_a", "subnet_b", "security_group", "instance_1", "instance_2", "instance_3", "s3_bucket"],
        1: ["s3_bucket", "instance_2", "vpc", "instance_1", "subnet_b", "security_group", "subnet_a", "instance_3"],
        2: ["instance_3", "subnet_a", "s3_bucket", "security_group", "vpc", "instance_1", "subnet_b", "instance_2"],
        3: ["security_group", "instance_1", "subnet_b", "s3_bucket", "instance_3", "vpc", "instance_2", "subnet_a"],
        4: ["instance_1", "security_group", "instance_3", "subnet_a", "instance_2", "vpc", "s3_bucket", "subnet_b"],
    }
    seed_key = int(shuffle_seed)
    if seed_key not in shuffle_orders:
        seed_key = 0
    file_order = shuffle_orders[seed_key]
    listing_lines = ["{}. resource \"{}\"".format(i + 1, n) for i, n in enumerate(file_order)]
    listing_text = "File listing (this order is cosmetic only):\n" + "\n".join(listing_lines)

    text_panel = {
        "kind": "text",
        "text": listing_text,
        "caption": "Shuffle this list and watch the timeline above: it does not move, because the file's order carries no ordering information at all.",
    }

    scalars_panel = {
        "kind": "scalars",
        "items": [
            {"label": "Total apply time", "value": float(total_time), "unit": "s"},
            {"label": "Concurrency (model setting)", "value": float(conc), "unit": ""},
        ],
        "value_format": ".1f",
    }

    if conc >= 2:
        order_note = ("At this concurrency, s3_bucket starts immediately alongside vpc: nothing in the graph "
                       "connects them, so both begin at time zero regardless of where s3_bucket sits in the file listing.")
    else:
        order_note = ("At concurrency 1 only one resource runs at a time. The row order above is one valid serial "
                       "order; several different orderings would satisfy this same graph equally well.")

    if conc >= 3:
        width_note = (" Total time has already flattened to the critical path length: the widest level of this "
                       "graph has three nodes, so raising concurrency past 3 finishes the apply no sooner.")
    else:
        width_note = ""

    return {
        "kind": "stack",
        "panels": [grid_panel, text_panel, scalars_panel],
        "caption": order_note + width_note,
    }


