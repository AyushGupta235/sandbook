def plan_action(config, state, real, force_new=False):
    if config is None and state is None:
        return "no change"
    if config is not None and state is None:
        return "create"
    if config is None and state is not None:
        return "destroy"
    if real is None:
        return "create"
    if config == state == real:
        return "no change"
    if config == real and state != real:
        return "no change"
    if config != real:
        return "replace" if force_new else "update in place"
    return "no change"


